export type AppInfo = {
  name: string;
  version: string;
  /** "win32", "darwin"… */
  platform: string;
  /** Global shortcut that opens the question box (e.g. Ctrl+Shift+Space). */
  askShortcut: string | null;
  /** Global shortcut to ask by voice (e.g. Ctrl+Shift+O). */
  talkShortcut: string | null;
};

export interface OttoBridge {
  app: {
    info(): Promise<AppInfo>;
    /** The global shortcut was pressed. Returns the unsubscribe function. */
    onFocusQuestion(listener: () => void): () => void;
    /** The talk shortcut was pressed. */
    onStartListening(listener: () => void): () => void;
  };
  autostart: {
    /** Starts with Windows (minimized to the notification area). */
    get(): Promise<boolean>;
    set(enabled: boolean): Promise<boolean>;
  };
  session: {
    get(): Promise<SessionState>;
    login(request: LoginRequest): Promise<LoginResult>;
    logout(): Promise<void>;
    /** Returns the unsubscribe function. */
    onChange(listener: (state: SessionState) => void): () => void;
  };
  assistant: {
    ask(request: AskRequest): Promise<AskResult>;
    askByVoice(request: VoiceAskRequest): Promise<AskResult>;
    voiceSettings(): Promise<VoiceSettings>;
    /** Saves "listen for the name" in the account settings. */
    setWakeWord(enabled: boolean): Promise<boolean>;
  };
  account: {
    settings(): Promise<AccountResult<AccountSettings>>;
    updateSettings(
      change: SettingsChange,
    ): Promise<AccountResult<AccountSettings>>;
    updateName(name: string): Promise<AccountResult<string>>;
    searchPlaces(name: string): Promise<AccountResult<Place[]>>;
    setLocation(place: Place): Promise<AccountResult<AccountSettings>>;
    newsSources(): Promise<AccountResult<NewsSource[]>>;
    suggestedNewsSources(): Promise<AccountResult<SuggestedNewsSource[]>>;
    addNewsSource(source: {
      url: string;
      category: string;
    }): Promise<AccountResult<NewsSource>>;
    updateNewsSource(change: {
      id: string;
      active?: boolean;
    }): Promise<AccountResult<NewsSource>>;
    removeNewsSource(id: string): Promise<AccountResult<boolean>>;
  };
  today: {
    weather(): Promise<AccountResult<TodayWeather>>;
    agenda(): Promise<AccountResult<TodayAgenda>>;
    news(): Promise<AccountResult<Headline[]>>;
  };
  briefing: {
    /** Today's briefing (generated by the API on demand). */
    today(): Promise<Briefing>;
    /** Writes it again with the current agenda, weather and news. */
    regenerate(): Promise<Briefing>;
    /** The scheduled briefing of the day is due. */
    onPresented(listener: (briefing: Briefing) => void): () => void;
  };
  wake: {
    enable(name: string): Promise<WakeStatus>;
    disable(): Promise<WakeStatus>;
    status(): Promise<WakeStatus>;
    /** Streams microphone audio (16 kHz mono) to the local listener. */
    sendAudio(samples: Float32Array): void;
    /** Pause while Otto records, thinks or speaks. */
    setPaused(paused: boolean): void;
    onHeard(listener: (event: WakeEvent) => void): () => void;
    onStatus(listener: (status: WakeStatus) => void): () => void;
  };
}
